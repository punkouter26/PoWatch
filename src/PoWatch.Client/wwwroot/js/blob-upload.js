(() => {
  window.powatchBlobUpload = {
    async uploadSvgPlaceholder(sasUrl, label) {
      const svg = `
        <svg xmlns="http://www.w3.org/2000/svg" width="1280" height="720" viewBox="0 0 1280 720">
          <rect width="1280" height="720" fill="#111827" />
          <rect x="40" y="40" width="1200" height="640" rx="24" fill="#1f2937" stroke="#38ffa8" stroke-width="4" />
          <text x="80" y="150" fill="#38ffa8" font-size="46" font-family="Segoe UI, Arial">PoWatch Evidence Capture</text>
          <text x="80" y="250" fill="#d1d5db" font-size="32" font-family="Segoe UI, Arial">${label ?? 'Significant observation'}</text>
          <text x="80" y="320" fill="#9ca3af" font-size="24" font-family="Segoe UI, Arial">Generated by direct client upload flow</text>
        </svg>`;

      const blob = new Blob([svg], { type: 'image/svg+xml' });

      const response = await fetch(sasUrl, {
        method: 'PUT',
        headers: {
          'x-ms-blob-type': 'BlockBlob',
          'x-ms-blob-content-type': 'image/svg+xml',
          'content-type': 'image/svg+xml'
        },
        body: blob
      });

      if (!response.ok) {
        const details = await response.text();
        throw new Error(`Upload failed: ${response.status} ${details}`);
      }
    }
  };
})();
